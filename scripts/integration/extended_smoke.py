#!/usr/bin/env python3
"""Real public file lifecycle: upload -> ClamAV -> clean download, with tenant checks."""
import argparse
import json
import time
import urllib.request
from pathlib import Path
from uuid import uuid4
from smoke import Client

p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);a=p.parse_args()
c=Client('http://127.0.0.1:8080');c.login()
products=c.call('/api/v1/products?companyId=company-a')['items']
product=products[0]
created=c.call('/api/v1/applications','POST',{'companyId':'company-a','productId':product['productId'],'productVersion':product['version'],'need':{'purpose':'Оборотные средства','amount':{'amountMinor':50000000,'currency':'RUB'},'termMonths':12}},extra={'Idempotency-Key':str(uuid4())})
app=created['applicationId']
requirements=c.call('/api/v1/applications/'+app+'/document-requirements')
requirement=next(r for r in requirements['items'] if 'image/png' in r['allowedContentTypes'])
# Valid PNG generated by the same installed Pillow dependency as the OCR service.
import base64,subprocess
raw=subprocess.check_output(['docker','compose','exec','-T','ocr','python','-c',"import io,base64;from PIL import Image,ImageDraw;im=Image.new('RGB',(600,300),'white');ImageDraw.Draw(im).text((30,30),'Synthetic financial report',fill='black');s=io.BytesIO();im.save(s,format='PNG');print(base64.b64encode(s.getvalue()).decode())"])
content=base64.b64decode(raw)
intent=c.call('/api/v1/applications/'+app+'/documents/upload-intents','POST',{'fileName':'synthetic.png','declaredMimeType':'image/png','sizeBytes':len(content),'documentType':'FINANCIAL_STATEMENT','requirementId':requirement['requirementId'],'requirementsVersion':requirements['requirementsVersion']},extra={'Idempotency-Key':str(uuid4())})
headers={'Content-Type':'image/png','X-Upload-Grant':intent['grant'],'X-CSRF-Token':c.session['csrfToken'],'X-Company-Context':str(c.session['contextVersion'])}
with c.http.open(urllib.request.Request(c.base+intent['uploadUrl'],data=content,method='PUT',headers=headers),timeout=30) as r:assert r.status==204
for _ in range(90):
    doc=c.call('/api/v1/documents/'+intent['documentId'])
    if doc['scanState']=='CLEAN':break
    time.sleep(2)
else:raise AssertionError('ClamAV did not promote file to CLEAN')
download=c.call('/api/v1/documents/'+doc['documentId']+'/download-intents','POST')
with c.http.open(urllib.request.Request(c.base+download['downloadUrl'],headers={'X-Download-Grant':download['grant'],'X-Company-Context':str(c.session['contextVersion'])}),timeout=30) as r:assert r.read()==content
other=Client(c.base);other.login('representative-b','company-b');other.call('/api/v1/documents/'+doc['documentId'],expected=404)
report={'passed':True,'checks':['public upload','real ClamAV CLEAN','exact-byte clean download','cross-company 404'],'ocrExtraction':'BLOCKED_LLM_API_KEY_MISSING'}
a.output.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report))
