from typing import Protocol


class LLMClient(Protocol):
    async def complete(self, messages: list[dict], tools: list[dict], parameters: dict): ...


class SessionStore(Protocol):
    def create(self, user_id: str, company_id: str, prompt: str, parameters: dict): ...
    def get(self, session_id: str, token: str): ...
    def close(self, session_id: str, token: str): ...


class KnowledgeRepository(Protocol):
    def active_chunks(self) -> list[dict]: ...
    def version(self, document_id: str, version: int) -> dict: ...


class VectorIndex(Protocol):
    def upsert(self, chunks: list[dict], vectors: list[list[float]]): ...
    def search(self, vector: list[float], active_ids: list[str]) -> list[tuple[str, float]]: ...
    def reset(self): ...


class WebSearch(Protocol):
    async def search(self, query: str) -> list[dict]: ...


class BankGateway(Protocol):
    def products(self) -> dict: ...
    def application(self, application_id: str, company_id: str) -> dict: ...
    def documents(self, args, company_id: str) -> dict: ...
